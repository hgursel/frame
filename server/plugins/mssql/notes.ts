/**
 * Mechanical validation is what separates a useful note from a confident invention: a note that
 * annotates a column this object does not have is not evidence about anything.
 */
export function validateNote(parsed: any, object: any): SchemaNote | undefined {
  if (!parsed || typeof parsed !== 'object') return undefined;
  const purpose = text(parsed.purpose, 600);
  if (!purpose) return undefined;
  const known = new Map(
    columnNames(String(object.text || '')).map((c) => [c.toLowerCase(), c] as const),
  );
  const columnNotes: Record<string, string> = {};
  let invented = 0;
  for (const [key, value] of Object.entries(parsed.columnNotes || {})) {
    const actual = known.get(text(key, 128).toLowerCase());
    const meaning = text(value, 300);
    if (!actual || !meaning) {
      invented++;
      continue;
    }
    if (Object.keys(columnNotes).length < 60) columnNotes[actual] = meaning;
  }
  const confidence = ['high', 'medium', 'low'].includes(parsed.confidence)
    ? parsed.confidence
    : 'low';
  return {
    purpose,
    grain: text(parsed.grain, 200),
    domain: text(parsed.domain, 60),
    aliases: list(parsed.aliases, MAX_ALIASES, 60),
    columnNotes,
    // A model that annotated columns this object does not have was not reading the facts.
    confidence: invented > Object.keys(columnNotes).length ? 'low' : confidence,
    invented,
  };
}
/** Column names as the generated page lists them, which is what the model was shown. */
export function columnNames(page: string) {
  const start = page.indexOf('## Columns');
  const end = page.indexOf('## Relationships');
  if (start < 0 || end < start) return [];
  return page
    .slice(start, end)
    .split('\n')
    .map((line) => line.split('|')[2]?.trim())
    .filter((name): name is string => !!name && name !== 'Column' && !/^-+$/.test(name));
}
/** Connected components of the foreign-key graph, largest first. */
export function components(objects: any[]) {
  const index = new Map(
    objects.map((o) => [`${o.database || ''}.${o.schema}.${o.name}`.toLowerCase(), o] as const),
  );
  const parent = new Map<any, any>(objects.map((o) => [o, o] as const));
  const find = (o: any): any => {
    let root = o;
    while (parent.get(root) !== root) root = parent.get(root);
    while (parent.get(o) !== root) {
      const next = parent.get(o);
      parent.set(o, root);
      o = next;
    }
    return root;
  };
  for (const object of objects)
    for (const ref of JSON.parse(object.refs || '[]')) {
      const other = index.get(`${object.database || ''}.${String(ref)}`.toLowerCase());
      if (!other || other === object) continue;
      const [a, b] = [find(object), find(other)];
      if (a !== b) parent.set(a, b);
    }
  const groups = new Map<any, any[]>();
  for (const object of objects) {
    const root = find(object);
    if (!groups.has(root)) groups.set(root, []);
    groups.get(root)!.push(object);
  }
  return [...groups.values()].sort((a, b) => b.length - a.length);
}
