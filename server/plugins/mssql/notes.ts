/**
 * The generated page is the complete set of catalog facts about an object, so its hash is what
 * decides whether a saved note still describes reality. Re-running skips everything unchanged.
 */
export const factHashOf = (page: string) => {
  // Import timestamps are provenance, not catalog facts. Unchanged imports must keep notes reusable.
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(page);
  if (!match) return createHash('sha256').update(page).digest('hex');
  const metadata = YAML.parse(match[1]!);
  if (metadata?.generated) delete metadata.generated.at;
  return createHash('sha256')
    .update(JSON.stringify(metadata) + match[2])
    .digest('hex');
};
/** The bounded excerpt an enrichment prompt is built from. */
function factsOf(object: any) {
  const body = String(object.text || '');
  const columns = body.slice(body.indexOf('## Columns'), body.indexOf('## Keys and indexes'));
  return [
    `${object.database}.${object.schema}.${object.name}`,
    object.kind,
    `rows=${object.rowCount ?? 0}`,
    `referencedBy=${object.refCount ?? 0}`,
    columns,
  ]
    .join('\n')
    .slice(0, 9000);
}
